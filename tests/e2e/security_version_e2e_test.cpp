/* --- Helpers --- */

static sumo_validator_t *MakeValidator() {
    sumo_validator_t *v = sumo_validator_create(
        kSignPub, sizeof(kSignPub), nullptr);
    return v;
}

/* In-memory storage backend for the policy round-trip test. */
struct FakeStorage {
    std::unordered_map<std::string, uint64_t> u64;
    std::unordered_map<std::string, int64_t>  i64;
};

extern "C" {
static int fake_read_u64(const char *key, uint64_t *value, void *ctx) {
    auto *s = static_cast<FakeStorage *>(ctx);
    auto it = s->u64.find(key);
    if (it == s->u64.end()) return -1;
    *value = it->second;
    return 0;
}
static int fake_write_u64(const char *key, uint64_t value, void *ctx) {
    static_cast<FakeStorage *>(ctx)->u64[key] = value;
    return 0;
}
static int fake_read_i64(const char *key, int64_t *value, void *ctx) {
    auto *s = static_cast<FakeStorage *>(ctx);
    auto it = s->i64.find(key);
    if (it == s->i64.end()) return -1;
    *value = it->second;
    return 0;
}
static int fake_write_i64(const char *key, int64_t value, void *ctx) {
    static_cast<FakeStorage *>(ctx)->i64[key] = value;
    return 0;
}
}

static sumo_storage_ops_t MakeOps(FakeStorage *s) {
    sumo_storage_ops_t ops{};
    ops.read_u64  = fake_read_u64;
    ops.write_u64 = fake_write_u64;
    ops.read_i64  = fake_read_i64;
    ops.write_i64 = fake_write_i64;
    ops.ctx = s;
    return ops;
}

/* --- Tests --- */

TEST(SecurityVersionTest, AccessorReturnsValueWhenPresent) {
    sumo_validator_t *v = MakeValidator();
    ASSERT_NE(v, nullptr);

    sumo_manifest_t *m = nullptr;
    ASSERT_EQ(sumo_validate_envelope(v, kEnvelopeSecVer5,
                                     sizeof(kEnvelopeSecVer5), 0, &m),
              SUMO_OK);

    uint64_t sec_ver = 0;
    EXPECT_EQ(sumo_manifest_security_version(m, 0, &sec_ver), SUMO_OK);
    EXPECT_EQ(sec_ver, 5u);

    sumo_manifest_free(m);
    sumo_validator_free(v);
}

TEST(SecurityVersionTest, AccessorReturnsUnsupportedWhenAbsent) {
    sumo_validator_t *v = MakeValidator();
    ASSERT_NE(v, nullptr);

    sumo_manifest_t *m = nullptr;
    ASSERT_EQ(sumo_validate_envelope(v, kEnvelopeNoSecVer,
                                     sizeof(kEnvelopeNoSecVer), 0, &m),
              SUMO_OK);

    uint64_t sec_ver = 999;
    EXPECT_EQ(sumo_manifest_security_version(m, 0, &sec_ver),
              SUMO_ERR_UNSUPPORTED);
    EXPECT_EQ(sec_ver, 999u);  /* untouched on miss */

    sumo_manifest_free(m);
    sumo_validator_free(v);
}

TEST(SecurityVersionTest, FloorBelowValuePasses) {
    sumo_validator_t *v = MakeValidator();
    ASSERT_NE(v, nullptr);
    ASSERT_EQ(sumo_validator_set_min_security_version(v, 4), SUMO_OK);

    sumo_manifest_t *m = nullptr;
    EXPECT_EQ(sumo_validate_envelope(v, kEnvelopeSecVer5,
                                     sizeof(kEnvelopeSecVer5), 0, &m),
              SUMO_OK);
    EXPECT_NE(m, nullptr);

    sumo_manifest_free(m);
    sumo_validator_free(v);
}

TEST(SecurityVersionTest, FloorAtValueRejects) {
    sumo_validator_t *v = MakeValidator();
    ASSERT_NE(v, nullptr);
    ASSERT_EQ(sumo_validator_set_min_security_version(v, 5), SUMO_OK);

    sumo_manifest_t *m = nullptr;
    EXPECT_EQ(sumo_validate_envelope(v, kEnvelopeSecVer5,
                                     sizeof(kEnvelopeSecVer5), 0, &m),
              SUMO_ERR_ROLLBACK_REJECTED);
    EXPECT_EQ(m, nullptr);

    sumo_validator_free(v);
}

TEST(SecurityVersionTest, FloorIgnoredForManifestWithoutParameter) {
    /* A manifest that does not declare security_version is unaffected by
     * the floor — sequence_number anti-rollback still applies separately. */
    sumo_validator_t *v = MakeValidator();
    ASSERT_NE(v, nullptr);
    ASSERT_EQ(sumo_validator_set_min_security_version(v, 999), SUMO_OK);

    sumo_manifest_t *m = nullptr;
    EXPECT_EQ(sumo_validate_envelope(v, kEnvelopeNoSecVer,
                                     sizeof(kEnvelopeNoSecVer), 0, &m),
              SUMO_OK);
    EXPECT_NE(m, nullptr);

    sumo_manifest_free(m);
    sumo_validator_free(v);
}

TEST(SecurityVersionTest, PolicySaveLoadRoundTrip) {
    FakeStorage storage;
    sumo_storage_ops_t ops = MakeOps(&storage);

    /* First validator: validate the secver=5 envelope, then policy_save. */
    {
        sumo_validator_t *v = MakeValidator();
        ASSERT_NE(v, nullptr);

        sumo_manifest_t *m = nullptr;
        ASSERT_EQ(sumo_validate_envelope(v, kEnvelopeSecVer5,
                                         sizeof(kEnvelopeSecVer5), 0, &m),
                  SUMO_OK);
        ASSERT_EQ(sumo_policy_save(m, &ops), 0);

        sumo_manifest_free(m);
        sumo_validator_free(v);
    }

    /* Storage now holds the floor */
    EXPECT_EQ(storage.u64["sumo_sec_ver"], 5u);

    /* Second validator: policy_load applies floor=5; same envelope rejected. */
    {
        sumo_validator_t *v = MakeValidator();
        ASSERT_NE(v, nullptr);
        ASSERT_EQ(sumo_policy_load(v, &ops), 0);

        sumo_manifest_t *m = nullptr;
        EXPECT_EQ(sumo_validate_envelope(v, kEnvelopeSecVer5,
                                         sizeof(kEnvelopeSecVer5), 0, &m),
                  SUMO_ERR_ROLLBACK_REJECTED);
        EXPECT_EQ(m, nullptr);

        sumo_validator_free(v);
    }
}
